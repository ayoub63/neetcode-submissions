class Solution:
    def carFleet(self, target: int, position: List[int], speed: List[int]) -> int:
        cars = list(zip(position, speed))
        cars.sort(reverse=True)
        fleets = []
        curr_car_time = 0 
        
        for pos, spd in cars:
            time = (target - pos) / spd

            if time > curr_car_time:
                fleets.append(time)
                curr_car_time = time

        return len(fleets) 





        


































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































